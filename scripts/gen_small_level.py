#!/usr/bin/env python3
"""Generates levels/ffa_small.lvl: the small, open free-for-all arena (HALF = 44, 88 x 88 m, about 1/8 of ffa.lvl).

    python3 scripts/gen_small_level.py [out.lvl]

Design: contact in seconds, not minutes. One floor with a low lip and open void gaps; a stepped ziggurat with a 13 m
pylon (grapple perch) in the middle; two wall-run lanes (5.6 m between the faces, 8 m walls) on opposite corners; four
low cover blocks and two monolith walls that break sight lines without hiding anyone for long; two floating anchor
slabs at 11 m (rope highways, power-up perches). 10 spawns, 4 pickups. Point-symmetric (180 degrees) wherever it can
be. Cfg limits used: single jump 1.6 m, jump + double ~2.8 m, wall-run 11 m/s for 1.5 s, ramps 20 deg, grapple 40 m.
Tests: crates/shinobi-sim/tests/arena_small.rs
"""
import math
import sys

HALF = 44.0
R20 = 0.35
RAMP_RUN = 1.7498 * math.cos(R20)  # horizontal half-length of a 1.2 m ramp at 20 degrees


def slope_box(xa, ya, xb, yb, hz, th=0.25):
    """A ramp whose TOP surface runs from (xa, ya) to (xb, yb) (any x order), `th` thick, `hz` half width."""
    if xb < xa:
        xa, ya, xb, yb = xb, yb, xa, ya
    theta = math.atan2(yb - ya, xb - xa)
    length = math.hypot(xb - xa, yb - ya)
    return ((xa + xb) / 2 + th * math.sin(theta), (ya + yb) / 2 - th * math.cos(theta), 0, length / 2, th, hz, theta)


def tier_ramps():
    # ground -> tier 1 ramps exist already; tier 1 (1.2) -> tier 2 (2.4) over x 9..6, tier 2 -> tier 3 (3.6) over x 6..3.5
    out = []
    for sgn in (1, -1):
        out.append(slope_box(sgn * 9.0, 1.2, sgn * 6.0, 2.4, 3.0))
        out.append(slope_box(sgn * 6.0, 2.4, sgn * 3.5, 3.6, 2.5))
    return out


def f(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


boxes = []  # (title, [(cx, cy, cz, hx, hy, hz, rot)])


def part(title, items, rot180=False, mx=False):
    items = [b if len(b) == 7 else tuple(b) + (0,) for b in items]
    out = []
    for b in items:
        vs = [b]
        if mx:
            vs += [(-b[0], b[1], b[2], b[3], b[4], b[5], -b[6]) for b in vs]
        if rot180:
            vs += [(-b[0], b[1], -b[2], b[3], b[4], b[5], b[6]) for b in vs]
        for v in vs:
            if v not in out:
                out.append(v)
    boxes.append((title, out))


h = HALF
part("ground: one floor, open void beyond it (kill plane y = -20)", [(0, -0.5, 0, h, 0.5, h)])

# void lip: 1 m jumpable lip with a 12 m open gap in the middle of every side (fall in = kill plane)
seg = (h + 6.0) / 2.0
half_seg = (h - 6.0) / 2.0
part(
    "void lip (0.3 m curb, 12 m gaps)",
    [
        (-seg, 0.15, -h + 0.25, half_seg, 0.15, 0.25, 0),
        (-seg, 0.15, h - 0.25, half_seg, 0.15, 0.25, 0),
        (-h + 0.25, 0.15, -seg, 0.25, 0.15, half_seg, 0),
        (-h + 0.25, 0.15, seg, 0.25, 0.15, half_seg, 0),
    ],
    rot180=True,
)

# hub: three tiers (tops 1.2 / 2.4 / 3.6), a 13 m pylon, ramps west + east onto the first tier
part(
    "hub ziggurat + pylon",
    [
        (0, 0.6, 0, 9, 0.6, 9, 0),
        (0, 1.8, 0, 6, 0.6, 6, 0),
        (0, 3.0, 0, 3.5, 0.6, 3.5, 0),
        (0, 8.0, 0, 1.2, 5.0, 1.2, 0),
        (9 + RAMP_RUN, 0.4591, 0, 1.7498, 0.15, 3.0, -R20),
        (-(9 + RAMP_RUN), 0.4591, 0, 1.7498, 0.15, 3.0, R20),
    ]
    + tier_ramps(),
)

# wall-run lanes: two 8 m walls, 5.6 m between the faces, 20 m long, NW and (rotated) SE
part(
    "wall-run lanes",
    [
        (-24, 4, -28, 10, 4, 0.5, 0),
        (-24, 4, -34.6, 10, 4, 0.5, 0),
    ],
    rot180=True,
)

# low cover (jumpable, 1.6 m) around the hub, four corners of a square
part("cover pillars (3.2 m: full walls, nothing waist high)", [(15, 1.6, 15, 1.5, 1.6, 1.5, 0)], mx=True, rot180=False)
part("cover pillars (z mirror)", [(15, 1.6, -15, 1.5, 1.6, 1.5, 0)], mx=True)

# monoliths: 6 m x 4 m x 1 m slabs that split the diagonals
part("monoliths", [(-8, 3, -14, 2, 3, 0.5, 0)], rot180=True)

# floating anchor slabs: rope highways and power-up perches
part("anchor slabs", [(-27, 11, 0, 5, 0.4, 5, 0)], rot180=True)

spawns = [
    (-34, -10), (34, 10),   # west / east flanks
    (-20, -6), (20, 6),     # inner ring
    (-14, 34), (14, -34),   # lane mouths
    (-30, 28), (30, -28),   # opposite corners
    (-8, 20), (8, -20),     # between the hub and the lanes
]
pickups = [
    (-27, 12.4, 0, 25), (27, 12.4, 0, 25),  # on the anchor slabs
    (0, 1, 24, 20), (0, 1, -24, 20),         # contested ground
]

lines = [
    "# SHINOBI FFA SMALL - 88 x 88 m free-for-all arena (open void edges, kill plane y=-20): contact in seconds.",
    "# GENERATED by scripts/gen_small_level.py (HALF=44). Edit the script, not this file; tests: crates/shinobi-sim/tests/arena_small.rs",
    "# x right, y up. A stepped hub with a 13 m pylon, two wall-run lanes, low cover, two monoliths, two 11 m anchor slabs.",
    "",
]
n = 0
for title, items in boxes:
    lines.append("# --- %s ---" % title)
    for (cx, cy, cz, hx, hy, hz, rot) in items:
        row = "box %s %s %s  %s %s %s" % (f(cx), f(cy), f(cz), f(hx), f(hy), f(hz))
        if rot:
            row += " " + f(rot)
        lines.append(row)
        n += 1
    lines.append("")
lines.append("# --- %d spawns (open ground, spread so players meet within seconds) ---" % len(spawns))
for x, z in spawns:
    lines.append("spawn %s 0.81 %s" % (f(x), f(z)))
lines.append("")
lines.append("# --- %d pickups ---" % len(pickups))
for x, y, z, r in pickups:
    lines.append("pickup %s %s %s %s" % (f(x), f(y), f(z), f(r)))

out = sys.argv[1] if len(sys.argv) > 1 else "levels/ffa_small.lvl"
open(out, "w").write("\n".join(lines) + "\n")
print("wrote %s: %d boxes, %d spawns, %d pickups" % (out, n, len(spawns), len(pickups)))
