def boxes(name):
    """[(kind, cx, cy, cz, hx, hy, hz)] for one level: the panels first, then their anchors."""
    out = [("panel",) + tuple(p) for p, a in RUNWALLS[name]]
    out += [("anchor",) + tuple(a) for p, a in RUNWALLS[name] if a is not None]
    return out


def bricks(name, seg=6.0):
    """Like `boxes`, but every panel is cut into equal pieces of at most `seg` m along its long axis (the destructible maps keep
    bricks to 2..6 m). Pieces butt exactly, so they stand on each other's side as well as on the deck."""
    out = []
    for kind, cx, cy, cz, hx, hy, hz in boxes(name):
        if kind != "panel" or max(hx, hz) * 2 <= seg + 1e-6:
            out.append((kind, cx, cy, cz, hx, hy, hz))
            continue
        n = int(-(-max(hx, hz) * 2 // seg))
        along_x = hx > hz
        half = (hx if along_x else hz) / n
        for i in range(n):
            off = -(hx if along_x else hz) + half * (2 * i + 1)
            out.append((kind, cx + off, cy, cz, half, hy, hz) if along_x else (kind, cx, cy, cz + off, hx, hy, half))
    return out


def count(name):
    return len(RUNWALLS[name])


def _fmt(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def patch_level_file(path, name, before="# --- 8 spawns"):
    """Hand-written level files without a generator (levels/arena.lvl): insert the run-wall boxes just before the line that starts
    with `before`, replacing any earlier run-wall section. Idempotent.
        python3 scripts/runwalls.py levels/arena.lvl arena"""
    marker = "# --- run walls"
    lines = open(path).read().split("\n")
    if any(l.startswith(marker) for l in lines):
        i = next(k for k, l in enumerate(lines) if l.startswith(marker))
        j = next(k for k in range(i + 1, len(lines)) if lines[k].startswith("# ---"))
        del lines[i:j]
    at = next(k for k, l in enumerate(lines) if l.startswith(before))
    sec = [marker + " (scripts/runwalls.py): 20 m x 7 m wall-run panels, each with a hook anchor 8 m past its end and 2 m above its top ---"]
    for kind, cx, cy, cz, hx, hy, hz in boxes(name):
        sec.append("box %s %s %s  %s %s %s" % tuple(_fmt(v) for v in (cx, cy, cz, hx, hy, hz)))
    sec.append("")
    lines[at:at] = sec
    open(path, "w").write("\n".join(lines))


