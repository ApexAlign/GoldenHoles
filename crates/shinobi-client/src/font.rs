//! 5x7 bitmap font for the HUD (uppercase, digits, a little punctuation). Renderer-agnostic data:
//! each glyph is 7 rows, bit 4 = leftmost column. Lowercase maps to uppercase; unknown chars draw as `?`.

pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;
/// Columns from one glyph origin to the next (5 + 1 gap).
pub const ADVANCE: usize = 6;

const fn g(r: [u8; 7]) -> [u8; 7] {
    r
}

pub fn glyph(c: char) -> [u8; 7] {
    match c.to_ascii_uppercase() {
        ' ' => g([0; 7]),
        '0' => g([0b01110, 0b10001, 0b10011, 0b10101, 0b11001, 0b10001, 0b01110]),
        '1' => g([0b00100, 0b01100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110]),
        '2' => g([0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b01000, 0b11111]),
        '3' => g([0b11111, 0b00010, 0b00100, 0b00010, 0b00001, 0b10001, 0b01110]),
        '4' => g([0b00010, 0b00110, 0b01010, 0b10010, 0b11111, 0b00010, 0b00010]),
        '5' => g([0b11111, 0b10000, 0b11110, 0b00001, 0b00001, 0b10001, 0b01110]),
        '6' => g([0b00110, 0b01000, 0b10000, 0b11110, 0b10001, 0b10001, 0b01110]),
        '7' => g([0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b01000, 0b01000]),
        '8' => g([0b01110, 0b10001, 0b10001, 0b01110, 0b10001, 0b10001, 0b01110]),
        '9' => g([0b01110, 0b10001, 0b10001, 0b01111, 0b00001, 0b00010, 0b01100]),
        'A' => g([0b01110, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001]),
        'B' => g([0b11110, 0b10001, 0b10001, 0b11110, 0b10001, 0b10001, 0b11110]),
        'C' => g([0b01110, 0b10001, 0b10000, 0b10000, 0b10000, 0b10001, 0b01110]),
        'D' => g([0b11100, 0b10010, 0b10001, 0b10001, 0b10001, 0b10010, 0b11100]),
        'E' => g([0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b11111]),
        'F' => g([0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b10000]),
        'G' => g([0b01110, 0b10001, 0b10000, 0b10111, 0b10001, 0b10001, 0b01111]),
        'H' => g([0b10001, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001]),
        'I' => g([0b01110, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110]),
        'J' => g([0b00111, 0b00010, 0b00010, 0b00010, 0b00010, 0b10010, 0b01100]),
        'K' => g([0b10001, 0b10010, 0b10100, 0b11000, 0b10100, 0b10010, 0b10001]),
        'L' => g([0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b11111]),
        'M' => g([0b10001, 0b11011, 0b10101, 0b10101, 0b10001, 0b10001, 0b10001]),
        'N' => g([0b10001, 0b11001, 0b10101, 0b10011, 0b10001, 0b10001, 0b10001]),
        'O' => g([0b01110, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01110]),
        'P' => g([0b11110, 0b10001, 0b10001, 0b11110, 0b10000, 0b10000, 0b10000]),
        'Q' => g([0b01110, 0b10001, 0b10001, 0b10001, 0b10101, 0b10010, 0b01101]),
        'R' => g([0b11110, 0b10001, 0b10001, 0b11110, 0b10100, 0b10010, 0b10001]),
        'S' => g([0b01111, 0b10000, 0b10000, 0b01110, 0b00001, 0b00001, 0b11110]),
        'T' => g([0b11111, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100]),
        'U' => g([0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01110]),
        'V' => g([0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01010, 0b00100]),
        'W' => g([0b10001, 0b10001, 0b10001, 0b10101, 0b10101, 0b10101, 0b01010]),
        'X' => g([0b10001, 0b10001, 0b01010, 0b00100, 0b01010, 0b10001, 0b10001]),
        'Y' => g([0b10001, 0b10001, 0b01010, 0b00100, 0b00100, 0b00100, 0b00100]),
        'Z' => g([0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b10000, 0b11111]),
        '.' => g([0, 0, 0, 0, 0, 0, 0b00100]),
        ':' => g([0, 0b00100, 0b00100, 0, 0b00100, 0b00100, 0]),
        '!' => g([0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0, 0b00100]),
        '%' => g([0b11001, 0b11010, 0b00010, 0b00100, 0b01000, 0b01011, 0b10011]),
        '-' => g([0, 0, 0, 0b11111, 0, 0, 0]),
        '/' => g([0b00001, 0b00010, 0b00010, 0b00100, 0b01000, 0b01000, 0b10000]),
        '+' => g([0, 0b00100, 0b00100, 0b11111, 0b00100, 0b00100, 0]),
        '?' | _ => g([0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0, 0b00100]),
    }
}

/// Width of `text` in glyph columns (no trailing gap).
pub fn text_cols(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { n * ADVANCE - (ADVANCE - GLYPH_W) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_fit_five_bits_and_are_distinct() {
        let mut seen = std::collections::HashSet::new();
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:!%-/+?".chars() {
            let gl = glyph(c);
            assert!(gl.iter().all(|r| *r < 32), "{c}");
            assert!(seen.insert(gl), "duplicate bitmap for {c}");
        }
    }

    #[test]
    fn lowercase_maps_unknown_is_question_mark_and_width() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), glyph('?'));
        assert_eq!(text_cols(""), 0);
        assert_eq!(text_cols("A"), 5);
        assert_eq!(text_cols("AB"), 11);
    }
}
